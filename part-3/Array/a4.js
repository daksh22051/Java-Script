//array method


//push method - add element at last 
let cars = ["maruti", "defender" , "xuv800"]
cars.push("aulto")
console.log(cars);
cars.push("honda")
console.log(cars);



//pop - delete the element at last 
cars.pop()
console.log(cars); //delete "honda"
cars.pop()
console.log(cars); //delete "aulto"






